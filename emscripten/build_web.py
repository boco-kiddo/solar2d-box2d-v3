#!/usr/bin/env python3
"""
Builds plugin.box2dv3 for Solar2D HTML5 (emscripten).

Solar2D's HTML5 engine cannot load native plugins at run time: require() finds a C plugin only when the engine's
wasm exports its luaopen_ function (platform/emscripten/Rtt_EmscriptenCPluginLoader.cpp). So the plugin is built
as a static library and linked into the engine's webtemplate.zip by the Solar2D source tree's
platform/emscripten/build_web.py (its --plugin option).

    python emscripten/build_web.py --corona D:/corona_s2d --emsdk C:/emsdk                  # -> emscripten/build/<config>/libplugin_box2dv3.a
    python emscripten/build_web.py --corona D:/corona_s2d --emsdk C:/emsdk --template       # + webtemplate.zip with the plugin
    python emscripten/build_web.py --corona D:/corona_s2d --emsdk C:/emsdk --install "C:/Program Files (x86)/Corona Labs/Corona"
    python emscripten/build_web.py --corona D:/corona_s2d --emsdk C:/emsdk --app Corona --out web/index.html

Several plugins in one engine: --with path/libplugin_x.a (repeatable) links other plugin libraries too, e.g. the
one plugin.s3d's emscripten/build_web.py makes. Each --install replaces the whole template, so list them all.

Options: --config Release|Debug, --simd (WebAssembly SIMD: faster, needs Chrome 91+, Firefox 89+, Safari 16.4+),
--jobs N, --verbose, --clean. Without --corona, SOLAR2D_ROOT is used. Without --emsdk, emcc must be on PATH or
EMSDK must be set (same rules as the engine's script, which this one reuses).

Built single threaded (the engine is built without pthreads): physics.setThreadCount() keeps 1 thread.
"""

import argparse
import concurrent.futures
import glob
import importlib.util
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SHARED = os.path.join(ROOT, "shared")
BUILD = os.path.join(HERE, "build")
LIB_NAME = "libplugin_box2dv3.a"


def log(msg):
    print("[box2dv3-web] " + msg, flush=True)


def fail(msg):
    print("[box2dv3-web] ERROR: " + msg, file=sys.stderr, flush=True)
    sys.exit(1)


def load_engine_script(corona):
    """The Solar2D tree's platform/emscripten/build_web.py, imported for its emsdk setup."""
    path = os.path.join(corona, "platform", "emscripten", "build_web.py")
    if not os.path.isfile(path):
        fail("no platform/emscripten/build_web.py in %s (pass --corona <Solar2D source folder>)" % corona)
    spec = importlib.util.spec_from_file_location("solar2d_build_web", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod, path


def rename_header(out_dir):
    """The engine also links Box2D 2.x, a C++ library whose classes share names with Box2D 3's C structs (b2Vec2,
    b2Rot, b2Transform, b2BodyDef, ...). Inline functions and templates the plugin's C++ instantiates with those
    types (std::vector<b2Vec2>, ...) would then have the same mangled names as the engine's, and the linker keeps
    only one copy, possibly the 2.x one (b2Rot even has another field order). The plugin's C++ files are compiled
    with Box2D 3's type names renamed to b2v3_*: only C++ mangling changes, the C functions keep their names."""
    names = set()
    for f in glob.glob(os.path.join(SHARED, "include", "box2d", "*.h")):
        s = open(f, encoding="utf-8").read()
        s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
        s = re.sub(r"//.*", "", s)
        names.update(re.findall(r"typedef\s+(?:struct|enum|union)\s+(\w+)\s*\{", s))
        names.update(re.findall(r"\}\s*(\w+)\s*;", s))
        names.update(re.findall(r"typedef\s+[^;{}()]*?\b(\w+)\s*;", s))
    names = sorted(n for n in names if n.startswith("b2"))
    if "b2Vec2" not in names:
        fail("could not read the Box2D type names from shared/include/box2d")
    path = os.path.join(out_dir, "b2v3_rename.h")
    text = "// generated by emscripten/build_web.py: Box2D 3 type names for the plugin's C++ files\n" + \
        "".join("#define %s b2v3_%s\n" % (n, n[2:]) for n in names)
    if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    return path


def needs_build(obj, dep):
    if not os.path.isfile(obj) or not os.path.isfile(dep):
        return True
    t = os.path.getmtime(obj)
    text = open(dep, encoding="utf-8", errors="replace").read().replace("\\\r\n", " ").replace("\\\n", " ")
    m = re.search(r"\.o:\s", text)
    for f in re.split(r"(?<!\\)\s+", text[m.end():] if m else text):
        f = f.replace("\\ ", " ").strip()
        if f and os.path.isfile(f) and os.path.getmtime(f) > t:
            return True
    return False


def build_library(engine, corona, emsdk, config, simd, jobs, verbose):
    env, emcc, empp, emar = engine.setup_emsdk(emsdk)
    out_dir = os.path.join(BUILD, config + ( "-simd" if simd else "" ))
    obj_dir = os.path.join(out_dir, "obj")
    os.makedirs(obj_dir, exist_ok=True)

    corona_inc = os.path.join(corona, "librtt", "Corona")
    lua_inc = os.path.join(corona, "external", "lua-5.1.3", "src")
    for d, f in ((corona_inc, "CoronaLua.h"), (lua_inc, "lua.h")):
        if not os.path.isfile(os.path.join(d, f)):
            fail("missing %s in %s" % (f, d))

    common = ["-O0", "-g"] if config == "Debug" else ["-O2", "-DNDEBUG"]
    common += ["-msimd128", "-msse2"] if simd else ["-DBOX2D_DISABLE_SIMD"]
    # gnu17, not c17: timer.c uses POSIX clock_gettime, which strict C hides in emscripten's headers
    c_flags = common + ["-std=gnu17", "-I" + os.path.join(SHARED, "include")]
    cxx_flags = common + ["-std=c++17", "-fno-exceptions", "-fno-rtti", "-include", rename_header(out_dir),
                          "-I" + os.path.join(SHARED, "include"), "-I" + os.path.join(SHARED, "plugin"),
                          "-I" + corona_inc, "-I" + lua_inc]

    sources = [(f, "c") for f in sorted(glob.glob(os.path.join(SHARED, "src", "*.c")))]
    sources += [(f, "c++") for f in sorted(glob.glob(os.path.join(SHARED, "plugin", "*.cpp")))]
    tasks, objs = [], []
    for src, lang in sources:
        name = ("c_" if lang == "c" else "p_") + os.path.splitext(os.path.basename(src))[0]
        obj, dep = os.path.join(obj_dir, name + ".o"), os.path.join(obj_dir, name + ".d")
        objs.append(obj)
        if needs_build(obj, dep):
            cmd = [emcc if lang == "c" else empp] + (c_flags if lang == "c" else cxx_flags) + \
                ["-MMD", "-MF", dep, "-c", src, "-o", obj]
            tasks.append((src, cmd))

    if tasks:
        log("compiling %d file(s)" % len(tasks))
        errors = []

        def compile_one(task):
            src, cmd = task
            if verbose:
                log(" ".join(cmd))
            r = subprocess.run(cmd, env=env, capture_output=True, text=True)
            if r.returncode != 0:
                errors.append((src, r.stdout + r.stderr))

        with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
            list(pool.map(compile_one, tasks))
        if errors:
            for src, text in errors[:10]:
                sys.stderr.write("\n=== %s\n%s" % (src, text))
            fail("%d file(s) failed to compile" % len(errors))

    lib = os.path.join(out_dir, LIB_NAME)
    if tasks or not os.path.isfile(lib):
        if os.path.isfile(lib):
            os.remove(lib)
        rsp = lib + ".rsp"
        with open(rsp, "w", encoding="utf-8") as f:
            f.write("\n".join('"%s"' % o.replace("\\", "/") for o in objs))
        r = subprocess.run([emar, "rcs", lib, "@" + rsp], env=env, capture_output=True, text=True)
        if r.returncode != 0:
            fail("emar failed:\n" + r.stdout + r.stderr)
    log("-> " + lib)
    return lib


def main():
    p = argparse.ArgumentParser(description="Build plugin.box2dv3 for Solar2D HTML5 (emscripten).")
    p.add_argument("--corona", default=os.environ.get("SOLAR2D_ROOT"), help="Solar2D source folder (default: SOLAR2D_ROOT)")
    p.add_argument("--emsdk", help="emsdk folder (default: emcc on PATH or EMSDK)")
    p.add_argument("--config", default="Release", choices=["Release", "Debug"])
    p.add_argument("--simd", action="store_true", help="WebAssembly SIMD (Chrome 91+, Firefox 89+, Safari 16.4+)")
    p.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2)))
    p.add_argument("--template", action="store_true", help="also build the engine's webtemplate.zip with the plugin")
    p.add_argument("--install", metavar="SIMULATOR_DIR", help="build webtemplate.zip and copy it into this Simulator")
    p.add_argument("--app", metavar="PROJECT_DIR", help="build one project directly with the plugin (for testing)")
    p.add_argument("--out", default="app/index.html", help="output .html for --app")
    p.add_argument("--with", dest="others", action="append", default=[], metavar="LIB.a",
                   help="another plugin library to link into the same engine, e.g. libplugin_s3d.a (repeatable)")
    p.add_argument("--sdl", type=int, default=2, choices=[2, 3], help="passed to the engine's script")
    p.add_argument("--clean", action="store_true")
    p.add_argument("--verbose", action="store_true")
    a = p.parse_args()

    if a.clean:
        shutil.rmtree(BUILD, ignore_errors=True)
        log("removed " + BUILD)
        return
    if not a.corona:
        fail("pass --corona <Solar2D source folder> or set SOLAR2D_ROOT")
    corona = os.path.abspath(a.corona)
    engine, engine_script = load_engine_script(corona)
    lib = build_library(engine, corona, a.emsdk, a.config, a.simd, a.jobs, a.verbose)

    if a.template or a.install or a.app:
        cmd = [sys.executable, engine_script, "--config", a.config, "--jobs", str(a.jobs), "--sdl", str(a.sdl),
               "--plugin", lib]
        for other in a.others:
            cmd += ["--plugin", os.path.abspath(other)]
        if a.emsdk:
            cmd += ["--emsdk", a.emsdk]
        if a.verbose:
            cmd.append("--verbose")
        if a.app:
            cmd += ["--app", os.path.abspath(a.app), "--out", os.path.abspath(a.out)]
        elif a.install:
            cmd += ["--install", a.install]
        log("engine: " + " ".join('"%s"' % c if " " in c else c for c in cmd[1:]))
        r = subprocess.run(cmd)
        if r.returncode != 0:
            fail("the engine build failed")


if __name__ == "__main__":
    main()
